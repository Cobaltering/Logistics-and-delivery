create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  created_user_id uuid;
begin
  insert into public.users (user_id, role_id, full_name, email)
  values (
    new.id,
    (select role_id from public.roles where role_name = 'Customer'),
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), split_part(new.email, '@', 1)),
    new.email
  )
  returning user_id into created_user_id;

  insert into public.customers (user_id, contact_no, address)
  values (
    created_user_id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'contact_no'), ''), 'Not provided'),
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'address'), ''), 'Not provided')
  );
  return new;
end;
$$;

