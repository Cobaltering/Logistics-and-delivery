create or replace function public.require_delivery_proof()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = 'Delivered' and not exists (
    select 1 from public.delivery_proof p where p.shipment_id = new.shipment_id
  ) then
    raise exception 'Delivery proof is required';
  end if;
  return new;
end;
$$;

drop trigger if exists shipment_delivery_proof_required on public.shipments;
create trigger shipment_delivery_proof_required
  before update of status on public.shipments
  for each row execute function public.require_delivery_proof();

-- Direct shipment status edits are blocked; statuses must come from a tracking event.
create or replace function public.prevent_direct_shipment_status_change()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status is distinct from old.status
     and current_setting('app.tracking_event_update', true) is distinct from 'true' then
    raise exception 'Shipment status changes must be recorded as tracking events';
  end if;
  return new;
end;
$$;

drop trigger if exists shipment_status_requires_event on public.shipments;
create trigger shipment_status_requires_event
  before update of status on public.shipments
  for each row execute function public.prevent_direct_shipment_status_change();

-- Create a shipment and its package details in one database transaction.
create or replace function public.create_shipment_with_package(
  p_recipient_name text,
  p_recipient_contact text,
  p_pickup_address text,
  p_delivery_address text,
  p_package_description text,
  p_package_weight_kg numeric,
  p_package_declared_value numeric default 0
)
returns table (shipment_id uuid, tracking_no text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  owner_customer_id uuid;
  created_shipment_id uuid;
  created_tracking_no text;
begin
  select c.customer_id into owner_customer_id
  from public.customers c
  where c.user_id = auth.uid();

  if owner_customer_id is null then
    raise exception 'A customer account is required to book a shipment';
  end if;
  if public.current_role_name() <> 'Customer' then
    raise exception 'Only customer accounts may book shipments';
  end if;

  insert into public.shipments as created (
    customer_id, recipient_name, recipient_contact, pickup_address, delivery_address
  ) values (
    owner_customer_id, p_recipient_name, p_recipient_contact, p_pickup_address, p_delivery_address
  )
  returning created.shipment_id, created.tracking_no
  into created_shipment_id, created_tracking_no;

  insert into public.packages (shipment_id, description, weight_kg, declared_value)
  values (
    created_shipment_id, p_package_description, p_package_weight_kg,
    coalesce(p_package_declared_value, 0)
  );

  return query select created_shipment_id, created_tracking_no;
end;
$$;

revoke all on function public.create_shipment_with_package(text, text, text, text, text, numeric, numeric) from public;
grant execute on function public.create_shipment_with_package(text, text, text, text, text, numeric, numeric) to authenticated;

