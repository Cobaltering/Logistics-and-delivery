-- Logistics and Delivery Management System
-- Run once in the Supabase SQL Editor. Tables are protected by RLS.

-- 1. Reference tables and user profiles: define the roles, account data, and warehouse assignments.
create table if not exists public.roles (
  role_id bigint generated by default as identity primary key,
  role_name text not null unique
);

insert into public.roles (role_name) values
  ('Administrator'),
  ('Operations Manager'),
  ('Dispatcher'),
  ('Warehouse Staff'),
  ('Delivery Rider'),
  ('Customer'),
  ('Finance Officer')
on conflict (role_name) do nothing;

create table if not exists public.warehouses (
  warehouse_id uuid primary key default gen_random_uuid(),
  name text not null,
  address text not null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now()
);

create table if not exists public.users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role_id bigint not null references public.roles(role_id),
  full_name text not null check (length(trim(full_name)) between 1 and 100),
  email text not null unique,
  status text not null default 'active' check (status in ('active', 'inactive', 'locked')),
  warehouse_id uuid references public.warehouses(warehouse_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  customer_id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.users(user_id) on delete cascade,
  contact_no text not null,
  address text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.vehicles (
  vehicle_id uuid primary key default gen_random_uuid(),
  plate_number text not null unique,
  vehicle_type text not null,
  status text not null default 'available' check (status in ('available', 'in use', 'maintenance', 'inactive')),
  created_at timestamptz not null default now()
);

create table if not exists public.riders (
  rider_id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.users(user_id) on delete cascade,
  vehicle_id uuid references public.vehicles(vehicle_id),
  license_no text,
  created_at timestamptz not null default now()
);

create table if not exists public.routes (
  route_id uuid primary key default gen_random_uuid(),
  route_name text not null,
  origin text not null,
  destination text not null,
  created_by uuid references public.users(user_id),
  created_at timestamptz not null default now()
);

-- 2. Shipment lifecycle: shipments, package details, rider assignments, and append-only tracking history.
create table if not exists public.shipments (
  shipment_id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(customer_id),
  tracking_no text not null unique default ('LDS-' || upper(replace(gen_random_uuid()::text, '-', ''))),
  recipient_name text not null check (length(trim(recipient_name)) between 1 and 100),
  recipient_contact text not null,
  pickup_address text not null,
  delivery_address text not null,
  pickup_scheduled_at timestamptz,
  warehouse_id uuid references public.warehouses(warehouse_id),
  status text not null default 'Created'
    check (status in ('Created', 'Picked Up', 'In Transit', 'At Warehouse', 'Out for Delivery', 'Delivered', 'Failed Delivery', 'Lost', 'Suspicious', 'Cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.packages (
  package_id uuid primary key default gen_random_uuid(),
  shipment_id uuid not null unique references public.shipments(shipment_id) on delete cascade,
  description text not null check (length(trim(description)) between 1 and 150),
  weight_kg numeric(8,2) not null check (weight_kg > 0 and weight_kg <= 1000),
  declared_value numeric(12,2) not null default 0 check (declared_value >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.delivery_assignments (
  assignment_id uuid primary key default gen_random_uuid(),
  shipment_id uuid not null references public.shipments(shipment_id) on delete cascade,
  rider_id uuid not null references public.riders(rider_id),
  route_id uuid references public.routes(route_id),
  assigned_by uuid not null references public.users(user_id),
  assigned_at timestamptz not null default now(),
  completed_at timestamptz
);

create unique index if not exists one_active_assignment_per_shipment
  on public.delivery_assignments (shipment_id) where completed_at is null;

create table if not exists public.tracking_events (
  tracking_event_id uuid primary key default gen_random_uuid(),
  shipment_id uuid not null references public.shipments(shipment_id) on delete cascade,
  status text not null
    check (status in ('Created', 'Picked Up', 'In Transit', 'At Warehouse', 'Out for Delivery', 'Delivered', 'Failed Delivery', 'Lost', 'Suspicious', 'Cancelled')),
  location text,
  notes text,
  created_by uuid references public.users(user_id),
  created_at timestamptz not null default now()
);

create index if not exists tracking_events_shipment_created_idx
  on public.tracking_events (shipment_id, created_at);

-- 3. Delivery evidence, payments, customer complaints, incidents, and user notifications.
create table if not exists public.delivery_proof (
  proof_id uuid primary key default gen_random_uuid(),
  shipment_id uuid not null unique references public.shipments(shipment_id) on delete cascade,
  rider_id uuid not null references public.riders(rider_id),
  recipient_name text not null check (length(trim(recipient_name)) between 1 and 100),
  proof_url text not null check (length(trim(proof_url)) between 1 and 1000),
  delivered_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  payment_id uuid primary key default gen_random_uuid(),
  shipment_id uuid not null unique references public.shipments(shipment_id) on delete cascade,
  amount numeric(12,2) not null check (amount >= 0),
  payment_method text not null check (payment_method in ('Cash', 'Card', 'Bank Transfer', 'E-wallet', 'COD')),
  status text not null default 'Pending' check (status in ('Pending', 'Paid', 'Failed', 'Refunded')),
  reference_no text,
  recorded_by uuid references public.users(user_id),
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.complaints (
  complaint_id uuid primary key default gen_random_uuid(),
  shipment_id uuid not null references public.shipments(shipment_id) on delete cascade,
  customer_id uuid not null references public.customers(customer_id),
  subject text not null check (length(trim(subject)) between 1 and 120),
  description text not null check (length(trim(description)) between 1 and 2000),
  status text not null default 'Open' check (status in ('Open', 'In Progress', 'Resolved', 'Closed')),
  assigned_to uuid references public.users(user_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.incidents (
  incident_id uuid primary key default gen_random_uuid(),
  shipment_id uuid not null references public.shipments(shipment_id) on delete cascade,
  incident_type text not null check (incident_type in ('Lost', 'Suspicious', 'Other')),
  description text not null,
  status text not null default 'Open' check (status in ('Open', 'Investigating', 'Resolved', 'Closed')),
  reported_by uuid references public.users(user_id),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists public.notifications (
  notification_id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(user_id) on delete cascade,
  shipment_id uuid references public.shipments(shipment_id) on delete cascade,
  message text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  audit_log_id bigint generated by default as identity primary key,
  actor_id uuid references public.users(user_id) on delete set null,
  action text not null,
  table_name text not null,
  record_id text,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);

-- 4. Security helper functions: resolve the caller's role and limit shipment visibility by responsibility.
create or replace function public.current_role_name()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select r.role_name
  from public.users u
  join public.roles r on r.role_id = u.role_id
  where u.user_id = auth.uid()
    and u.status = 'active'
$$;

create or replace function public.current_warehouse_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select warehouse_id from public.users
  where user_id = auth.uid() and status = 'active'
$$;

create or replace function public.can_access_shipment(target_shipment_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.shipments s
    left join public.customers c on c.customer_id = s.customer_id
    where s.shipment_id = target_shipment_id
      and (
        c.user_id = auth.uid()
        or public.current_role_name() in ('Administrator', 'Operations Manager', 'Dispatcher', 'Finance Officer')
        or (
          public.current_role_name() = 'Warehouse Staff'
          and s.warehouse_id = public.current_warehouse_id()
        )
        or (
          public.current_role_name() = 'Delivery Rider'
          and exists (
            select 1
            from public.delivery_assignments da
            join public.riders rd on rd.rider_id = da.rider_id
            where da.shipment_id = s.shipment_id
              and da.completed_at is null
              and rd.user_id = auth.uid()
          )
        )
      )
  )
$$;

