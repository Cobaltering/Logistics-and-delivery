-- Every new tracking event updates the current shipment status and reports lost/suspicious incidents.
create or replace function public.handle_tracking_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_status text;
begin
  select s.status into current_status
  from public.shipments s
  where s.shipment_id = new.shipment_id
  for update;

  if not (
    (current_status = 'Created' and new.status in ('Created', 'Picked Up', 'Cancelled', 'Lost', 'Suspicious'))
    or (current_status = 'Picked Up' and new.status in ('In Transit', 'Lost', 'Suspicious'))
    or (current_status = 'In Transit' and new.status in ('At Warehouse', 'Out for Delivery', 'Lost', 'Suspicious'))
    or (current_status = 'At Warehouse' and new.status in ('In Transit', 'Out for Delivery', 'Lost', 'Suspicious'))
    or (current_status = 'Out for Delivery' and new.status in ('Delivered', 'Failed Delivery', 'Lost', 'Suspicious'))
    or (current_status = 'Failed Delivery' and new.status in ('Out for Delivery', 'Lost', 'Suspicious'))
  ) then
    raise exception 'Invalid shipment status transition from % to %', current_status, new.status;
  end if;

  if new.status = 'Delivered' and not exists (
    select 1 from public.delivery_proof p where p.shipment_id = new.shipment_id
  ) then
    raise exception 'Delivery proof must be recorded before marking a shipment Delivered';
  end if;

  perform set_config('app.tracking_event_update', 'true', true);
  update public.shipments
  set status = new.status, updated_at = now()
  where shipment_id = new.shipment_id;
  perform set_config('app.tracking_event_update', 'false', true);

  if new.status in ('Lost', 'Suspicious') then
    insert into public.incidents (shipment_id, incident_type, description, reported_by)
    values (new.shipment_id, new.status, coalesce(new.notes, new.status || ' shipment reported'), new.created_by);
  end if;
  return new;
end;
$$;

drop trigger if exists tracking_event_apply on public.tracking_events;
create trigger tracking_event_apply
  after insert on public.tracking_events
  for each row execute function public.handle_tracking_event();

