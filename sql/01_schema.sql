    public.current_role_name() in ('Administrator', 'Operations Manager', 'Dispatcher')
    or (public.current_role_name() = 'Warehouse Staff' and warehouse_id = public.current_warehouse_id())
  ) with check (
    public.current_role_name() in ('Administrator', 'Operations Manager', 'Dispatcher')
    or (public.current_role_name() = 'Warehouse Staff' and warehouse_id = public.current_warehouse_id())
  );

