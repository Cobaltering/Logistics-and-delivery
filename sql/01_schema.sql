-- 5. Audit and automatic timestamps: preserve who changed important records and when.
create or replace function public.write_audit_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_value jsonb;
  new_value jsonb;
  row_value jsonb;
  row_id text;
begin
  if tg_op <> 'INSERT' then old_value := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then new_value := to_jsonb(new); end if;
  row_value := coalesce(new_value, old_value);
  row_id := coalesce(row_value ->> 'shipment_id', row_value ->> 'user_id',
                     row_value ->> 'customer_id', row_value ->> 'payment_id',
                     row_value ->> 'complaint_id', row_value ->> 'assignment_id',
                     row_value ->> 'tracking_event_id', row_value ->> 'audit_log_id');

  insert into public.audit_logs (actor_id, action, table_name, record_id, old_data, new_data)
  values (auth.uid(), tg_op, tg_table_name, row_id, old_value, new_value);

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

do $$
declare
  table_to_audit text;
begin
  foreach table_to_audit in array array[
    'users', 'customers', 'shipments', 'packages', 'delivery_assignments',
    'tracking_events', 'delivery_proof', 'payments', 'complaints', 'incidents'
  ] loop
    execute format('drop trigger if exists audit_%I on public.%I', table_to_audit, table_to_audit);
    execute format(
      'create trigger audit_%I after insert or update or delete on public.%I for each row execute function public.write_audit_log()',
      table_to_audit, table_to_audit
    );
  end loop;
end;
$$;

