-- A user assigned the Delivery Rider role automatically receives a rider profile.
create or replace function public.ensure_rider_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select role_name from public.roles where role_id = new.role_id) = 'Delivery Rider' then
    insert into public.riders (user_id)
    values (new.user_id)
    on conflict (user_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists create_rider_profile on public.users;
create trigger create_rider_profile
  after insert or update on public.users
  for each row execute function public.ensure_rider_profile();

